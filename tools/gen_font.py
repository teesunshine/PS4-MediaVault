#!/usr/bin/env python3
"""Generates src/font8x16.h (ASCII 32..126, 8x16 1-bit) from DejaVu Sans Mono.
DejaVu fonts are under a permissive license (Bitstream Vera / public domain changes)."""
from PIL import Image, ImageDraw, ImageFont
import sys
path = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
font = ImageFont.truetype(path, 14)
rows = []
for code in range(32, 127):
    img = Image.new("L", (8, 16), 0)
    d = ImageDraw.Draw(img)
    d.text((0, 0), chr(code), font=font, fill=255)
    glyph = []
    for y in range(16):
        b = 0
        for x in range(8):
            if img.getpixel((x, y)) > 110:
                b |= 0x80 >> x
        glyph.append(b)
    rows.append((code, glyph))
with open(sys.argv[1], "w") as f:
    f.write("/* Generated by tools/gen_font.py - do not edit. 8x16, ASCII 32..126. */\n")
    f.write("#ifndef MV_FONT8X16_H\n#define MV_FONT8X16_H\n")
    f.write("static const unsigned char MV_FONT8X16[95][16] = {\n")
    for code, g in rows:
        label = chr(code) if chr(code) not in "\\*/" else "?"
        f.write("    {" + ",".join("0x%02X" % b for b in g) + "}, /* %d %s */\n" % (code, label))
    f.write("};\n#endif\n")
